// Writes a migration that loads src/data/instances.json and events.json into
// the shared catalog tables. Rows are upserted, so running it again after
// editing the JSON ships the new content as a fresh migration.
//
//   node scripts/catalog-sql.mjs [name]      (default name: catalog_data)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const name = process.argv[2] ?? 'catalog_data';

function upserts(table, rows) {
  const values = rows.map((row) => {
    const json = JSON.stringify(row);
    if (json.includes('$json$')) throw new Error(`Row ${row.id} contains the quote marker $json$`);
    return `  (${quote(row.id)}, $json$${json}$json$::jsonb)`;
  });
  return (
    `insert into public.${table} (id, data) values\n${values.join(',\n')}\n` +
    `on conflict (id) do update set data = excluded.data, updated_at = now();\n`
  );
}

const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;
const load = (file) => JSON.parse(readFileSync(join(root, 'src/data', file), 'utf8'));

const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
const path = join(root, 'supabase/migrations', `${stamp}_${name}.sql`);
const sql =
  '-- Generated by scripts/catalog-sql.mjs from src/data/*.json. Edit the JSON, not this file.\n\n' +
  upserts('instance_catalog', load('instances.json')) +
  '\n' +
  upserts('event_catalog', load('events.json'));

writeFileSync(path, sql);
console.log(`Wrote ${path}`);
